export function plural(
  n: number,
  one: string,
  few: string,
  many: string,
): string {
  const ten = n % 10;
  const hundred = n % 100;
  if (ten === 1 && hundred !== 11) return one;
  if (ten >= 2 && ten <= 4 && (hundred < 12 || hundred > 14)) return few;
  return many;
}

/** Форма словаря — от русского; функции и массивы сохраняют сигнатуры */
type Shape<T> = T extends (...args: infer A) => string
  ? (...args: A) => string
  : T extends string
    ? string
    : T extends readonly (infer U)[]
      ? readonly Shape<U>[]
      : { [K in keyof T]: Shape<T[K]> };

export type Dictionary = Shape<typeof ru>;
